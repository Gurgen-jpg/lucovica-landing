/** Зона-подарок: на странице акции она исключается из списка зон для записи */
const GIFT_ZONE = 'Подмышки'
const CATEGORIES = ['laser-women', 'laser-men'] as const

const armpitsWomen = priceOf({ category: 'laser-women', item: GIFT_ZONE })!
const armpitsMen = priceOf({ category: 'laser-men', item: GIFT_ZONE })!

/** Группа цен без зоны-подарка: на неё по акции не записываются */
function withoutGift(id: string, label: string): PriceGroupDef {
  const g = groupFromCategory(id, label)
  return { ...g, items: g.items.filter((i) => i.name !== GIFT_ZONE) }
}

